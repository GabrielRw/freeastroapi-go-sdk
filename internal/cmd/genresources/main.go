// Command genresources generates the idiomatic resource layer of the SDK.
//
// It reads the vendored OpenAPI document and the low-level client that oapi-codegen generated
// from it (api/api.gen.go), then writes:
//
//   - resources_gen.go: the Client struct, one service type per resource and sub-resource,
//     and one method per operation that calls the low-level client;
//   - operations_gen.go: the Operations table mapping every operationId to its method.
//
// Operations are grouped by URL path, as in the TypeScript and Python SDKs: the first segment
// after the version is the resource, a second segment becomes a sub-resource when no
// operation sits directly on it, and the remaining segments form the method name. When the
// same method exists in several API versions, the latest version gets the plain name and
// older versions get a V1/V2 suffix.
//
// The generator matches operations to the low-level client by HTTP method and path (taken
// from the generated New<Op>Request functions), so it never has to re-implement
// oapi-codegen's naming rules. Run it through scripts/generate.sh.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

func main() {
	specPath := flag.String("spec", "spec/freeastro.json", "OpenAPI document")
	apiPath := flag.String("api", "api/api.gen.go", "low-level client generated by oapi-codegen")
	outDir := flag.String("out", ".", "directory for resources_gen.go and operations_gen.go")
	flag.Parse()

	if err := run(*specPath, *apiPath, *outDir); err != nil {
		fmt.Fprintln(os.Stderr, "genresources:", err)
		os.Exit(1)
	}
}

func run(specPath, apiPath, outDir string) error {
	spec, err := loadSpec(specPath)
	if err != nil {
		return err
	}
	ops, err := collectOperations(spec)
	if err != nil {
		return err
	}
	if err := assignNames(ops); err != nil {
		return err
	}
	low, err := parseLowLevel(apiPath)
	if err != nil {
		return err
	}
	if err := bind(ops, low); err != nil {
		return err
	}

	resources, err := renderResources(ops, low)
	if err != nil {
		return err
	}
	operations, err := renderOperations(ops)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(outDir, "resources_gen.go"), resources, 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(outDir, "operations_gen.go"), operations, 0o644); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "genresources: %d operations\n", len(ops))
	return nil
}

// ---------------------------------------------------------------- spec

type specDoc struct {
	Paths map[string]map[string]json.RawMessage `json:"paths"`
}

type specOperation struct {
	OperationID string                  `json:"operationId"`
	Summary     string                  `json:"summary"`
	Description string                  `json:"description"`
	Deprecated  bool                    `json:"deprecated"`
	RequestBody *specRequestBody        `json:"requestBody"`
	Responses   map[string]specResponse `json:"responses"`
}

type specRequestBody struct {
	Content map[string]json.RawMessage `json:"content"`
}

type specResponse struct {
	Content map[string]json.RawMessage `json:"content"`
}

func loadSpec(path string) (*specDoc, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var doc specDoc
	if err := json.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if len(doc.Paths) == 0 {
		return nil, fmt.Errorf("%s: no paths", path)
	}
	return &doc, nil
}

var httpMethods = []string{"get", "post", "put", "patch", "delete"}

// responseKind describes what a wrapper method returns.
type responseKind int

const (
	kindJSON      responseKind = iota // decoded JSON (typed, or json.RawMessage when untyped)
	kindContent                       // *Content (images, PDF, Markdown, ...)
	kindNoContent                     // error only
)

type operation struct {
	id          string
	method      string // upper case
	path        string
	summary     string
	description string
	deprecated  bool
	version     int
	resource    string   // first segment, e.g. "western"
	rest        []string // remaining segments
	sub         string   // sub-resource segment or ""
	baseName    string   // Go method name before the version suffix
	name        string   // Go method name
	accessor    []string // Go accessor path on the Client

	successCode  string // e.g. "200"
	kind         responseKind
	contentTypes []string // success content types, sorted
	mixed        bool     // JSON plus other success content types
	jsonBody     bool     // has an application/json request body
	rawBody      bool     // has only non-JSON request bodies

	low *lowOperation
}

var versionedPath = regexp.MustCompile(`^/api/v(\d+)/(.+)$`)

func collectOperations(spec *specDoc) ([]*operation, error) {
	paths := make([]string, 0, len(spec.Paths))
	for p := range spec.Paths {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var ops []*operation
	seen := map[string]bool{}
	for _, path := range paths {
		item := spec.Paths[path]
		for _, method := range httpMethods {
			raw, ok := item[method]
			if !ok {
				continue
			}
			var so specOperation
			if err := json.Unmarshal(raw, &so); err != nil {
				return nil, fmt.Errorf("%s %s: %w", strings.ToUpper(method), path, err)
			}
			if so.OperationID == "" {
				return nil, fmt.Errorf("%s %s has no operationId", strings.ToUpper(method), path)
			}
			if seen[so.OperationID] {
				return nil, fmt.Errorf("duplicate operationId %s", so.OperationID)
			}
			seen[so.OperationID] = true

			op := &operation{
				id:          so.OperationID,
				method:      strings.ToUpper(method),
				path:        path,
				summary:     strings.TrimSpace(so.Summary),
				description: strings.TrimSpace(so.Description),
				deprecated:  so.Deprecated,
				version:     1,
			}
			var segments []string
			if m := versionedPath.FindStringSubmatch(path); m != nil {
				op.version, _ = strconv.Atoi(m[1])
				segments = splitPath(m[2])
			} else {
				// Unversioned paths such as /natal: the single segment is the resource and
				// the method is called Simple, as in the other SDKs.
				segments = splitPath(path)
				if len(segments) == 1 {
					segments = append(segments, "simple")
				}
			}
			if len(segments) == 0 || isParam(segments[0]) {
				return nil, fmt.Errorf("cannot derive a resource from path %s", path)
			}
			op.resource = segments[0]
			op.rest = segments[1:]

			if so.RequestBody != nil {
				for ct := range so.RequestBody.Content {
					if isJSON(ct) {
						op.jsonBody = true
					}
				}
				op.rawBody = !op.jsonBody && len(so.RequestBody.Content) > 0
			}
			if err := classifyResponse(op, so.Responses); err != nil {
				return nil, err
			}
			ops = append(ops, op)
		}
	}
	return ops, nil
}

func classifyResponse(op *operation, responses map[string]specResponse) error {
	codes := make([]string, 0, len(responses))
	for code := range responses {
		if strings.HasPrefix(code, "2") {
			codes = append(codes, code)
		}
	}
	sort.Strings(codes) // "200" < "201" < "204" < "2XX"
	if len(codes) == 0 {
		op.successCode = "200"
		op.kind = kindNoContent
		return nil
	}
	op.successCode = codes[0]
	content := responses[op.successCode].Content
	if op.successCode == "204" || len(content) == 0 {
		op.kind = kindNoContent
		return nil
	}
	hasJSON := false
	for ct := range content {
		op.contentTypes = append(op.contentTypes, ct)
		if isJSON(ct) {
			hasJSON = true
		}
	}
	sort.Strings(op.contentTypes)
	switch {
	case hasJSON && len(content) == 1:
		op.kind = kindJSON
	case hasJSON:
		op.kind = kindJSON
		op.mixed = true
	default:
		op.kind = kindContent
	}
	return nil
}

func isJSON(contentType string) bool {
	ct := strings.ToLower(strings.TrimSpace(strings.SplitN(contentType, ";", 2)[0]))
	return ct == "application/json" || strings.HasSuffix(ct, "+json")
}

func splitPath(path string) []string {
	var out []string
	for _, s := range strings.Split(path, "/") {
		if s != "" {
			out = append(out, s)
		}
	}
	return out
}

func isParam(segment string) bool {
	return strings.HasPrefix(segment, "{") && strings.HasSuffix(segment, "}")
}

// ---------------------------------------------------------------- naming

// emptyNames names operations whose path has nothing after the resource.
var emptyNames = map[string]string{"v1_sky_events": "list"}

// defaultNames name operations whose path has no literal segment after the resource
// (e.g. GET /api/v1/natal/report/{job_id} is Natal.Report, but DELETE /api/v1/things/{id}
// is Things.Delete).
var defaultNames = map[string]string{"GET": "Get", "POST": "Create", "PUT": "Replace", "PATCH": "Update", "DELETE": "Delete"}

// initialisms are upper-cased when they form a whole word of a Go name.
var initialisms = map[string]bool{
	"ai": true, "api": true, "id": true, "kp": true, "qa": true, "svg": true, "png": true,
	"pdf": true, "url": true, "uri": true, "http": true, "json": true, "html": true,
	"ip": true, "utc": true, "uuid": true, "mcp": true, "sdk": true, "llm": true,
}

var wordSplit = regexp.MustCompile(`[^A-Za-z0-9]+`)

// goName turns "exact-aspects" into "ExactAspects" and "kp-render" into "KPRender".
func goName(text string) string {
	var b strings.Builder
	for _, word := range wordSplit.Split(text, -1) {
		if word == "" {
			continue
		}
		if initialisms[strings.ToLower(word)] {
			b.WriteString(strings.ToUpper(word))
			continue
		}
		r := []rune(word)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}

func literalSegments(segments []string) []string {
	var out []string
	for _, s := range segments {
		if !isParam(s) {
			out = append(out, s)
		}
	}
	return out
}

func assignNames(ops []*operation) error {
	// A second path segment becomes a sub-resource when no operation sits directly on it.
	direct := map[string]bool{}
	for _, o := range ops {
		if lit := literalSegments(o.rest); len(lit) == 1 {
			direct[o.resource+"/"+lit[0]] = true
		}
	}
	for _, o := range ops {
		lit := literalSegments(o.rest)
		nameParts := lit
		if len(lit) >= 2 && !isParam(o.rest[0]) && !direct[o.resource+"/"+o.rest[0]] {
			o.sub = o.rest[0]
			nameParts = lit[1:]
		}
		switch {
		case len(nameParts) > 0:
			o.baseName = goName(strings.Join(nameParts, "-"))
		case emptyNames[o.id] != "":
			o.baseName = goName(emptyNames[o.id])
		default:
			o.baseName = defaultNames[o.method]
		}
	}

	groups := map[string][]*operation{}
	for _, o := range ops {
		key := o.resource + "/" + o.sub + "/" + o.baseName
		groups[key] = append(groups[key], o)
	}
	for _, group := range groups {
		latest := 0
		for _, o := range group {
			if o.version > latest {
				latest = o.version
			}
		}
		perVersion := map[int]*operation{}
		for _, o := range group {
			if other, ok := perVersion[o.version]; ok {
				return fmt.Errorf("name clash: %s and %s", o.id, other.id)
			}
			perVersion[o.version] = o
			o.name = o.baseName
			if o.version != latest {
				o.name = fmt.Sprintf("%sV%d", o.baseName, o.version)
			}
		}
	}

	// Members of one Go struct (sub-resource fields, methods and Raw variants) must not collide.
	members := map[string]string{}
	claim := func(owner, member, kind string) error {
		key := owner + "." + member
		if prev, ok := members[key]; ok && prev != kind {
			return fmt.Errorf("member clash on %s (%s and %s)", key, prev, kind)
		}
		if prev, ok := members[key]; ok && kind != "sub" && prev == kind {
			return fmt.Errorf("duplicate method %s", key)
		}
		members[key] = kind
		return nil
	}
	for _, o := range ops {
		res := goName(o.resource)
		if err := claim("Client", res, "sub"); err != nil {
			return err
		}
		owner := res
		if o.sub != "" {
			if err := claim(res, goName(o.sub), "sub"); err != nil {
				return err
			}
			owner = res + "." + goName(o.sub)
		}
		if err := claim(owner, o.name, "method"); err != nil {
			return err
		}
		if o.mixed {
			if err := claim(owner, o.name+"Raw", "method"); err != nil {
				return err
			}
		}
		o.accessor = []string{res}
		if o.sub != "" {
			o.accessor = append(o.accessor, goName(o.sub))
		}
		o.accessor = append(o.accessor, o.name)
	}
	for _, reserved := range []string{"Do"} {
		if _, ok := members["Client."+reserved]; ok {
			return fmt.Errorf("resource name %s clashes with a Client method", reserved)
		}
	}
	return nil
}

// ---------------------------------------------------------------- low-level client

type lowOperation struct {
	goName       string
	withJSON     *ast.FuncDecl // <Op>WithResponse
	withBody     *ast.FuncDecl // <Op>WithBodyWithResponse
	response     *ast.StructType
	successField string   // JSON<code> field of the response struct, or ""
	successTyp   ast.Expr // its type, or nil
}

type lowLevel struct {
	byRoute map[string]string // "POST /api/v1/x/%s" -> Go operation name
	methods map[string]*ast.FuncDecl
	structs map[string]*ast.StructType
	aliases map[string]ast.Expr
}

func parseLowLevel(path string) (*lowLevel, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	low := &lowLevel{
		byRoute: map[string]string{},
		methods: map[string]*ast.FuncDecl{},
		structs: map[string]*ast.StructType{},
		aliases: map[string]ast.Expr{},
	}
	requestFunc := regexp.MustCompile(`^New([A-Za-z0-9_]+?)Request(WithBody)?$`)
	for _, decl := range file.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if d.Recv != nil {
				if recvName(d) == "ClientWithResponses" {
					low.methods[d.Name.Name] = d
				}
				continue
			}
			m := requestFunc.FindStringSubmatch(d.Name.Name)
			if m == nil || d.Body == nil {
				continue
			}
			method, route := requestRoute(d.Body)
			if method == "" || route == "" {
				continue
			}
			key := method + " " + route
			if prev, ok := low.byRoute[key]; ok && prev != m[1] {
				return nil, fmt.Errorf("two low-level operations for %s: %s and %s", key, prev, m[1])
			}
			low.byRoute[key] = m[1]
		case *ast.GenDecl:
			if d.Tok != token.TYPE {
				continue
			}
			for _, spec := range d.Specs {
				ts := spec.(*ast.TypeSpec)
				if ts.Assign.IsValid() {
					low.aliases[ts.Name.Name] = ts.Type
				} else if st, ok := ts.Type.(*ast.StructType); ok {
					low.structs[ts.Name.Name] = st
				}
			}
		}
	}
	return low, nil
}

func recvName(d *ast.FuncDecl) string {
	if d.Recv == nil || len(d.Recv.List) == 0 {
		return ""
	}
	t := d.Recv.List[0].Type
	if star, ok := t.(*ast.StarExpr); ok {
		t = star.X
	}
	if id, ok := t.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}

// requestRoute extracts the HTTP method and the fmt.Sprintf path template from a generated
// New<Op>Request function body.
func requestRoute(body *ast.BlockStmt) (method, route string) {
	ast.Inspect(body, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.AssignStmt:
			if len(x.Lhs) == 1 && len(x.Rhs) == 1 {
				if id, ok := x.Lhs[0].(*ast.Ident); ok && id.Name == "operationPath" {
					if call, ok := x.Rhs[0].(*ast.CallExpr); ok && isSelector(call.Fun, "fmt", "Sprintf") && len(call.Args) > 0 {
						if lit, ok := call.Args[0].(*ast.BasicLit); ok {
							route, _ = strconv.Unquote(lit.Value)
						}
					}
				}
			}
		case *ast.CallExpr:
			if (isSelector(x.Fun, "http", "NewRequest") || isSelector(x.Fun, "http", "NewRequestWithContext")) && len(x.Args) > 0 {
				arg := x.Args[0]
				if isSelector(x.Fun, "http", "NewRequestWithContext") && len(x.Args) > 1 {
					arg = x.Args[1]
				}
				switch a := arg.(type) {
				case *ast.BasicLit: // "POST"
					method, _ = strconv.Unquote(a.Value)
				case *ast.SelectorExpr: // http.MethodPost
					if strings.HasPrefix(a.Sel.Name, "Method") {
						method = strings.ToUpper(strings.TrimPrefix(a.Sel.Name, "Method"))
					}
				}
			}
		}
		return true
	})
	return method, route
}

func isSelector(e ast.Expr, pkg, name string) bool {
	sel, ok := e.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	id, ok := sel.X.(*ast.Ident)
	return ok && id.Name == pkg && sel.Sel.Name == name
}

var pathParam = regexp.MustCompile(`\{[^}]+\}`)

func bind(ops []*operation, low *lowLevel) error {
	var errs []error
	for _, o := range ops {
		route := o.method + " " + pathParam.ReplaceAllString(o.path, "%s")
		name, ok := low.byRoute[route]
		if !ok {
			errs = append(errs, fmt.Errorf("%s (%s %s): no low-level request function", o.id, o.method, o.path))
			continue
		}
		lo := &lowOperation{
			goName:   name,
			withJSON: low.methods[name+"WithResponse"],
			withBody: low.methods[name+"WithBodyWithResponse"],
			response: low.structs[name+"Response"],
		}
		if lo.response == nil {
			errs = append(errs, fmt.Errorf("%s: no %sResponse type", o.id, name))
			continue
		}
		if o.rawBody {
			if lo.withBody == nil {
				errs = append(errs, fmt.Errorf("%s: no %sWithBodyWithResponse method", o.id, name))
				continue
			}
		} else if lo.withJSON == nil {
			errs = append(errs, fmt.Errorf("%s: no %sWithResponse method", o.id, name))
			continue
		}
		if o.kind == kindJSON {
			// JSON200 for application/json; vendor types such as application/vnd.x+json get
			// a prefixed field (ApplicationvndXJSON200). Prefer the plain field.
			want := "JSON" + strings.ToUpper(o.successCode)
			for _, f := range lo.response.Fields.List {
				for _, n := range f.Names {
					if n.Name == want || (strings.HasSuffix(n.Name, want) && lo.successField == "") {
						lo.successField, lo.successTyp = n.Name, f.Type
					}
				}
			}
		}
		o.low = lo
	}
	return errors.Join(errs...)
}

// ---------------------------------------------------------------- rendering

const apiPkg = "github.com/GabrielRw/freeastroapi-go-sdk/api"

// runtimeTypeAliases are oapi-codegen runtime types re-exported by package api, so callers
// do not have to import the runtime package.
var runtimeTypeAliases = map[string]bool{"Date": true, "UUID": true, "Email": true, "File": true}

type renderer struct {
	imports map[string]string // path -> alias ("" for none)
	low     *lowLevel
}

func (r *renderer) use(path, alias string) { r.imports[path] = alias }

// typeString renders a type expression from package api for use in package freeastro.
func (r *renderer) typeString(e ast.Expr) (string, error) {
	switch t := e.(type) {
	case *ast.Ident:
		if isPredeclared(t.Name) {
			return t.Name, nil
		}
		if target, ok := r.low.aliases[t.Name]; ok {
			// Show the aliased type (e.g. NatalChartRequest rather than
			// V1NatalCalculateJSONRequestBody) when it is a plain named type.
			if id, ok := target.(*ast.Ident); ok && !isPredeclared(id.Name) {
				return r.typeString(id)
			}
		}
		r.use(apiPkg, "")
		return "api." + t.Name, nil
	case *ast.StarExpr:
		inner, err := r.typeString(t.X)
		return "*" + inner, err
	case *ast.ArrayType:
		if t.Len != nil {
			return "", fmt.Errorf("unsupported array type")
		}
		inner, err := r.typeString(t.Elt)
		return "[]" + inner, err
	case *ast.MapType:
		k, err := r.typeString(t.Key)
		if err != nil {
			return "", err
		}
		v, err := r.typeString(t.Value)
		return "map[" + k + "]" + v, err
	case *ast.InterfaceType:
		if t.Methods == nil || len(t.Methods.List) == 0 {
			return "any", nil
		}
	case *ast.SelectorExpr:
		pkg, _ := t.X.(*ast.Ident)
		if pkg == nil {
			break
		}
		switch pkg.Name {
		case "openapi_types":
			if runtimeTypeAliases[t.Sel.Name] {
				r.use(apiPkg, "")
				return "api." + t.Sel.Name, nil
			}
			r.use("github.com/oapi-codegen/runtime/types", "openapi_types")
			return "openapi_types." + t.Sel.Name, nil
		case "io", "time", "json":
			paths := map[string]string{"io": "io", "time": "time", "json": "encoding/json"}
			r.use(paths[pkg.Name], "")
			return pkg.Name + "." + t.Sel.Name, nil
		}
	}
	return "", fmt.Errorf("unsupported type expression %T", e)
}

func isPredeclared(name string) bool {
	switch name {
	case "bool", "string", "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16",
		"uint32", "uint64", "float32", "float64", "byte", "rune", "any", "error":
		return true
	}
	return false
}

func isUntyped(e ast.Expr) bool {
	if star, ok := e.(*ast.StarExpr); ok {
		e = star.X
	}
	switch t := e.(type) {
	case *ast.InterfaceType:
		return t.Methods == nil || len(t.Methods.List) == 0
	case *ast.Ident:
		return t.Name == "any"
	case *ast.MapType:
		if k, ok := t.Key.(*ast.Ident); ok && k.Name == "string" {
			return isUntyped(t.Value)
		}
	}
	return false
}

type param struct {
	name string
	typ  string
}

// lowParams returns the parameters of a low-level method between ctx and reqEditors.
func (r *renderer) lowParams(fn *ast.FuncDecl) ([]param, error) {
	var out []param
	fields := fn.Type.Params.List
	for i, f := range fields {
		if i == 0 { // ctx context.Context
			continue
		}
		if _, ok := f.Type.(*ast.Ellipsis); ok { // reqEditors ...RequestEditorFn
			continue
		}
		typ, err := r.typeString(f.Type)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", fn.Name.Name, err)
		}
		for _, n := range f.Names {
			out = append(out, param{name: n.Name, typ: typ})
		}
	}
	return out, nil
}

var reservedParams = map[string]bool{"ctx": true, "opts": true, "s": true, "resp": true, "err": true, "api": true}

func renderResources(ops []*operation, low *lowLevel) ([]byte, error) {
	r := &renderer{imports: map[string]string{"context": ""}, low: low}

	type service struct {
		typeName string
		path     []string // resource / sub segments, e.g. ["western", "progressions"]
		subs     []string // sub-resource segments
		ops      []*operation
	}
	services := map[string]*service{}
	var order []string
	get := func(path ...string) *service {
		key := strings.Join(path, "/")
		if s, ok := services[key]; ok {
			return s
		}
		name := ""
		for _, p := range path {
			name += goName(p)
		}
		s := &service{typeName: name + "Service", path: path}
		services[key] = s
		order = append(order, key)
		return s
	}
	var top []string
	for _, o := range ops {
		res := get(o.resource)
		if !contains(top, o.resource) {
			top = append(top, o.resource)
		}
		if o.sub == "" {
			res.ops = append(res.ops, o)
			continue
		}
		if !contains(res.subs, o.sub) {
			res.subs = append(res.subs, o.sub)
		}
		sub := get(o.resource, o.sub)
		sub.ops = append(sub.ops, o)
	}
	sort.Strings(top)
	sort.Strings(order)

	var body bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&body, format, args...) }

	// Client
	w("// Client is a FreeAstroAPI client. Create one with NewClient.\n")
	w("//\n// Operations are grouped by URL path: Client.Natal.Calculate calls\n")
	w("// POST /api/v1/natal/calculate and Client.Vedic.Panchang calls POST /api/v2/vedic/panchang.\n")
	w("// When an operation exists in several API versions, the plain method name calls the\n")
	w("// latest version and older versions carry a V1 or V2 suffix.\n")
	w("//\n// A Client is safe for concurrent use.\n")
	w("type Client struct {\n\tcore *core\n\n")
	for _, res := range top {
		s := services[res]
		w("\t// %s calls the /%s operations.\n", goName(res), res)
		w("\t%s *%s\n", goName(res), s.typeName)
	}
	w("}\n\n")
	w("func (c *Client) initServices() {\n")
	for _, res := range top {
		w("\tc.%s = new%s(c.core)\n", goName(res), services[res].typeName)
	}
	w("}\n\n")

	for _, key := range order {
		s := services[key]
		sort.Strings(s.subs)
		w("// %s calls the /%s operations. Use it through Client.%s.\n", s.typeName, strings.Join(s.path, "/"), strings.Join(accessorOf(s.path), "."))
		w("type %s struct {\n\tcore *core\n", s.typeName)
		if len(s.subs) > 0 {
			w("\n")
		}
		for _, sub := range s.subs {
			child := services[strings.Join(append(append([]string{}, s.path...), sub), "/")]
			w("\t// %s calls the /%s operations.\n", goName(sub), strings.Join(child.path, "/"))
			w("\t%s *%s\n", goName(sub), child.typeName)
		}
		w("}\n\n")
		w("func new%s(c *core) *%s {\n\treturn &%s{\n\t\tcore: c,\n", s.typeName, s.typeName, s.typeName)
		for _, sub := range s.subs {
			child := services[strings.Join(append(append([]string{}, s.path...), sub), "/")]
			w("\t\t%s: new%s(c),\n", goName(sub), child.typeName)
		}
		w("\t}\n}\n\n")

		sort.Slice(s.ops, func(i, j int) bool { return s.ops[i].name < s.ops[j].name })
		for _, o := range s.ops {
			if err := r.renderMethod(&body, s.typeName, o, false); err != nil {
				return nil, err
			}
			if o.mixed {
				if err := r.renderMethod(&body, s.typeName, o, true); err != nil {
					return nil, err
				}
			}
		}
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by internal/cmd/genresources from spec/freeastro.json. DO NOT EDIT.\n\n")
	out.WriteString("package freeastro\n\n")
	out.WriteString("import (\n")
	paths := make([]string, 0, len(r.imports))
	for p := range r.imports {
		paths = append(paths, p)
	}
	isModule := func(p string) bool { return strings.Contains(strings.SplitN(p, "/", 2)[0], ".") }
	sort.Slice(paths, func(i, j int) bool {
		if isModule(paths[i]) != isModule(paths[j]) {
			return !isModule(paths[i])
		}
		return paths[i] < paths[j]
	})
	for i, p := range paths {
		if i > 0 && isModule(p) && !isModule(paths[i-1]) {
			out.WriteString("\n") // standard library first, then modules
		}
		if alias := r.imports[p]; alias != "" {
			fmt.Fprintf(&out, "\t%s %q\n", alias, p)
		} else {
			fmt.Fprintf(&out, "\t%q\n", p)
		}
	}
	out.WriteString(")\n\n")
	out.Write(body.Bytes())
	return gofmt(out.Bytes(), "resources_gen.go")
}

func accessorOf(path []string) []string {
	out := []string{}
	for _, p := range path {
		out = append(out, goName(p))
	}
	return out
}

func contains(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

func (r *renderer) renderMethod(buf *bytes.Buffer, recv string, o *operation, raw bool) error {
	lo := o.low
	fn := lo.withJSON
	lowName := lo.goName + "WithResponse"
	if o.rawBody {
		fn = lo.withBody
		lowName = lo.goName + "WithBodyWithResponse"
	}
	params, err := r.lowParams(fn)
	if err != nil {
		return err
	}
	for i := range params {
		if reservedParams[params[i].name] {
			params[i].name += "Param"
		}
	}

	name := o.name
	kind := o.kind
	if raw {
		name += "Raw"
		kind = kindContent
	}
	var accept string
	switch kind {
	case kindJSON:
		var jsonTypes []string
		for _, ct := range o.contentTypes {
			if isJSON(ct) {
				jsonTypes = append(jsonTypes, ct)
			}
		}
		accept = strings.Join(jsonTypes, ", ")
	case kindContent:
		accept = strings.Join(o.contentTypes, ", ")
	}

	var result string
	switch kind {
	case kindJSON:
		if lo.successTyp == nil || isUntyped(lo.successTyp) {
			r.use("encoding/json", "")
			result = "json.RawMessage"
		} else {
			t, err := r.typeString(lo.successTyp)
			if err != nil {
				return fmt.Errorf("%s: %w", o.id, err)
			}
			if !strings.HasPrefix(t, "*") {
				t = "*" + t
			}
			result = t
		}
	case kindContent:
		result = "*Content"
	}

	// Doc comment.
	var doc []string
	doc = append(doc, fmt.Sprintf("%s calls %s %s (operation %s).", name, o.method, o.path, o.id))
	if o.summary != "" {
		doc = append(doc, "", o.summary+".")
		doc[len(doc)-1] = strings.TrimSuffix(doc[len(doc)-1], "..")
	}
	if o.description != "" {
		doc = append(doc, "")
		doc = append(doc, strings.Split(o.description, "\n")...)
	}
	switch {
	case raw:
		doc = append(doc, "", fmt.Sprintf("%sRaw returns the response body as sent, whatever its content type (%s).", o.name, strings.Join(o.contentTypes, ", ")))
	case kind == kindContent:
		doc = append(doc, "", fmt.Sprintf("The response body is returned as Content (%s).", strings.Join(o.contentTypes, ", ")))
	case kind == kindJSON && result == "json.RawMessage":
		doc = append(doc, "", "The API does not document this response's schema yet, so the JSON body is returned as is.")
	}
	if o.deprecated {
		doc = append(doc, "", "Deprecated: this operation is deprecated by the API.")
	}
	for _, line := range doc {
		line = strings.TrimRight(line, " \t")
		if line == "" {
			buf.WriteString("//\n")
		} else {
			buf.WriteString("// " + line + "\n")
		}
	}

	var sig, args []string
	sig = append(sig, "ctx context.Context")
	for _, p := range params {
		sig = append(sig, p.name+" "+p.typ)
		args = append(args, p.name)
	}
	sig = append(sig, "opts ...RequestOption")

	callCtx := fmt.Sprintf("s.core.call(ctx, %q, %q, opts)", o.id, accept)
	call := fmt.Sprintf("s.core.api.%s(%s)", lowName, strings.Join(append([]string{callCtx}, args...), ", "))

	switch kind {
	case kindNoContent:
		fmt.Fprintf(buf, "func (s *%s) %s(%s) error {\n", recv, name, strings.Join(sig, ", "))
		fmt.Fprintf(buf, "\t_, err := %s\n\treturn err\n}\n\n", call)
	case kindContent:
		fmt.Fprintf(buf, "func (s *%s) %s(%s) (*Content, error) {\n", recv, name, strings.Join(sig, ", "))
		fmt.Fprintf(buf, "\tresp, err := %s\n\tif err != nil {\n\t\treturn nil, err\n\t}\n", call)
		buf.WriteString("\treturn newContent(resp.HTTPResponse, resp.Body), nil\n}\n\n")
	case kindJSON:
		fmt.Fprintf(buf, "func (s *%s) %s(%s) (%s, error) {\n", recv, name, strings.Join(sig, ", "), result)
		fmt.Fprintf(buf, "\tresp, err := %s\n\tif err != nil {\n\t\treturn nil, err\n\t}\n", call)
		if result == "json.RawMessage" {
			buf.WriteString("\treturn rawJSON(resp.HTTPResponse, resp.Body)\n}\n\n")
		} else {
			fmt.Fprintf(buf, "\treturn decoded(resp.%s, resp.HTTPResponse, resp.Body)\n}\n\n", lo.successField)
		}
	}
	return nil
}

func renderOperations(ops []*operation) ([]byte, error) {
	sorted := append([]*operation(nil), ops...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].id < sorted[j].id })
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/cmd/genresources from spec/freeastro.json. DO NOT EDIT.\n\n")
	b.WriteString("package freeastro\n\n")
	fmt.Fprintf(&b, "// operations lists the %d operations of the vendored OpenAPI document.\n", len(ops))
	b.WriteString("var operations = []OperationInfo{\n")
	for _, o := range sorted {
		accessor := make([]string, len(o.accessor))
		for i, a := range o.accessor {
			accessor[i] = strconv.Quote(a)
		}
		fmt.Fprintf(&b, "\t{OperationID: %q, Method: %q, Path: %q, Accessor: []string{%s}, Deprecated: %t},\n",
			o.id, o.method, o.path, strings.Join(accessor, ", "), o.deprecated)
	}
	b.WriteString("}\n")
	return gofmt(b.Bytes(), "operations_gen.go")
}

func gofmt(src []byte, name string) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("%s: %w\n%s", name, err, src)
	}
	return out, nil
}
